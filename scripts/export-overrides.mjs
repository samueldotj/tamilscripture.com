#!/usr/bin/env node
// Export accepted corrections from Postgres into data/entities/overrides/
// (feature_dictionary.md §6). Run by .github/workflows/export-overrides.yml
// every 12 hours and on "Publish now". Needs SUPABASE_URL and
// SUPABASE_SERVICE_KEY (service role: bypasses RLS, read + mark exported).
//
// Output (deterministic, sorted):
//   overrides/names.toml                       [Name.VERSION] forms = ["…"]
//   overrides/articles/{source}/{slug}.toml    [[paragraphs]] id/text
//   overrides/lexicon.toml                     [H0430G] ta = "…" (Tamil glosses, concordance C5)
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

const url = process.env.SUPABASE_URL ?? 'https://zytgmnqmrvgspjdokajp.supabase.co';
const key = process.env.SUPABASE_SERVICE_KEY;
if (!key) {
	console.error('SUPABASE_SERVICE_KEY is not set');
	process.exit(2);
}
const root = process.argv[2] ?? 'data/entities/overrides';
const headers = { apikey: key, authorization: `Bearer ${key}`, 'content-type': 'application/json' };

const res = await fetch(`${url}/rest/v1/entity_accepted?select=target,text,accepted_at&order=target`, { headers });
if (!res.ok) {
	console.error('reading entity_accepted failed', res.status, await res.text());
	process.exit(1);
}
/** @type {{target: string, text: string, accepted_at: string}[]} */
const rows = await res.json();

// TOML basic strings accept the JSON escapes we produce.
const str = (s) => JSON.stringify(s);
const key_ = (k) => (/^[A-Za-z0-9_-]+$/.test(k) ? k : str(k));

const names = new Map(); // name_en → Map(version → row)
const articles = new Map(); // article id → rows
const glosses = new Map(); // Strong's number → row
let skipped = 0;
for (const r of rows) {
	if (r.target.startsWith('name:')) {
		const m = /^name:([A-Z0-9]+):(.+)$/.exec(r.target);
		if (!m) { skipped++; continue; }
		if (!names.has(m[2])) names.set(m[2], new Map());
		names.get(m[2]).set(m[1], r);
	} else if (r.target.startsWith('article:')) {
		const m = /^article:([a-z0-9]+\/[a-z0-9-]+)#(p[0-9]+-[0-9a-f]{8})$/.exec(r.target);
		if (!m) { skipped++; continue; }
		if (!articles.has(m[1])) articles.set(m[1], []);
		articles.get(m[1]).push({ id: `${m[1]}#${m[2]}`, ...r });
	} else if (r.target.startsWith('gloss:')) {
		const m = /^gloss:([HG][0-9]{4}[A-Za-z]?)$/.exec(r.target);
		if (!m) { skipped++; continue; }
		glosses.set(m[1], r);
	} else {
		skipped++;
	}
}

await mkdir(root, { recursive: true });
const header = '# Generated by scripts/export-overrides.mjs from accepted corrections. Do not edit by hand.\n';

let namesToml = header;
for (const name of [...names.keys()].sort()) {
	for (const [version, r] of [...names.get(name).entries()].sort()) {
		namesToml += `\n[${key_(name)}.${version}]\nforms = [${str(r.text)}]\naccepted_at = ${str(r.accepted_at)}\n`;
	}
}
await writeFile(path.join(root, 'names.toml'), namesToml);

let lexiconToml = header;
for (const num of [...glosses.keys()].sort()) {
	const r = glosses.get(num);
	lexiconToml += `
[${num}]
ta = ${str(r.text)}
accepted_at = ${str(r.accepted_at)}
`;
}
await writeFile(path.join(root, 'lexicon.toml'), lexiconToml);

// Rebuild the articles tree so nothing stale survives.
await rm(path.join(root, 'articles'), { recursive: true, force: true });
for (const id of [...articles.keys()].sort()) {
	const [source, slug] = id.split('/');
	let t = header;
	for (const p of articles.get(id).sort((a, b) => a.id.localeCompare(b.id))) {
		t += `\n[[paragraphs]]\nid = ${str(p.id)}\ntext = ${str(p.text)}\naccepted_at = ${str(p.accepted_at)}\n`;
	}
	await mkdir(path.join(root, 'articles', source), { recursive: true });
	await writeFile(path.join(root, 'articles', source, `${slug}.toml`), t);
}

// Mark everything exported.
const mark = await fetch(`${url}/rest/v1/entity_accepted?exported_at=is.null`, {
	method: 'PATCH',
	headers: { ...headers, prefer: 'return=minimal' },
	body: JSON.stringify({ exported_at: new Date().toISOString() })
});
if (!mark.ok) {
	console.error('marking exported_at failed', mark.status, await mark.text());
	process.exit(1);
}

const files = (await readdir(root, { recursive: true })).filter((f) => f.endsWith('.toml')).length;
console.log(`exported ${rows.length} accepted corrections (${names.size} names, ${articles.size} articles, ${glosses.size} glosses, ${skipped} skipped) into ${files} files under ${root}`);
